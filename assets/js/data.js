  function load() {
    let loaded = null;
    try {
      const raw = localStorage.getItem(KEY);
      if (raw) loaded = JSON.parse(raw);
    } catch (e) { storageOk = false; }
    if (!loaded || loaded.schema !== SCHEMA) { loaded = buildSeed(); api.db = loaded; save(); }
    api.db = loaded;
  }
  function save() {
    api.db.rev = (api.db.rev || 0) + 1;
    try { localStorage.setItem(KEY, JSON.stringify(api.db)); storageOk = true; }
    catch (e) { storageOk = false; console.warn('LocalStorage unavailable – changes will be lost on refresh.', e); }
  }

  function formatNumber(cfg, date, seq) {
    const parts = [cfg.prefix];
    if (cfg.includeYear) parts.push((date || U.today()).slice(0, 4));
    parts.push(U.pad(seq, Number(cfg.padding) || 4));
    return parts.filter(Boolean).join('-');
  }
  const COLLECTION_FOR = { quotation: 'quotations', invoice: 'invoices', receipt: 'payments', creditNote: 'creditNotes' };
  const FIELD_FOR = { quotation: 'number', invoice: 'number', receipt: 'receiptNumber', creditNote: 'number' };
  /** Preview the next number without consuming it. */
  function previewNumber(type, date) {
    const cfg = api.db.settings.numbering[type];
    return formatNumber(cfg, date, cfg.next);
  }
  /** Allocate the next unique number (skips any value already used in the local dataset). */
  function nextNumber(type, date) {
    const cfg = api.db.settings.numbering[type];
    const used = new Set(api.db[COLLECTION_FOR[type]].map(x => x[FIELD_FOR[type]]));
    let n = formatNumber(cfg, date, cfg.next);
    while (used.has(n)) { cfg.next++; n = formatNumber(cfg, date, cfg.next); }
    cfg.next++;
    return n;
  }
  function nextId(counter, prefix) {
    const c = api.db.settings.counters;
    const id = `${prefix}-${U.pad(c[counter]++, 4)}`;
    return id;
  }

